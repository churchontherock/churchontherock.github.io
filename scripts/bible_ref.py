"""
설교 제목·성경 본문 읽기 도우미.

영상 제목이나 설명란에서
    "믿으면 보리라" (요한복음 11장 30-44절)
    민수기 11장 4-6절, 10-20절 "죄는 예속이다 1"
같은 글을 찾아
    설교 제목: 믿으면 보리라
    본문(약어): 요11:30-44 / 민11:4-6, 10-20
으로 바꾼다. 약어는 개역개정 표준 약어.
"""

import re

# (정식 이름, 약어) — 개역개정 66권. 긴 이름부터 맞춰야 '요한일서'가 '요한'에 먹히지 않는다
BOOKS = [
    ("창세기", "창"), ("출애굽기", "출"), ("레위기", "레"), ("민수기", "민"), ("신명기", "신"),
    ("여호수아", "수"), ("사사기", "삿"), ("룻기", "룻"), ("사무엘상", "삼상"), ("사무엘하", "삼하"),
    ("열왕기상", "왕상"), ("열왕기하", "왕하"), ("역대상", "대상"), ("역대하", "대하"), ("에스라", "스"),
    ("느헤미야", "느"), ("에스더", "에"), ("욥기", "욥"), ("시편", "시"), ("잠언", "잠"),
    ("전도서", "전"), ("아가", "아"), ("이사야", "사"), ("예레미야애가", "애"), ("예레미야", "렘"),
    ("에스겔", "겔"), ("다니엘", "단"), ("호세아", "호"), ("요엘", "욜"), ("아모스", "암"),
    ("오바댜", "옵"), ("요나", "욘"), ("미가", "미"), ("나훔", "나"), ("하박국", "합"),
    ("스바냐", "습"), ("학개", "학"), ("스가랴", "슥"), ("말라기", "말"),
    ("마태복음", "마"), ("마가복음", "막"), ("누가복음", "눅"), ("요한복음", "요"), ("사도행전", "행"),
    ("로마서", "롬"), ("고린도전서", "고전"), ("고린도후서", "고후"), ("갈라디아서", "갈"), ("에베소서", "엡"),
    ("빌립보서", "빌"), ("골로새서", "골"), ("데살로니가전서", "살전"), ("데살로니가후서", "살후"),
    ("디모데전서", "딤전"), ("디모데후서", "딤후"), ("디도서", "딛"), ("빌레몬서", "몬"), ("히브리서", "히"),
    ("야고보서", "약"), ("베드로전서", "벧전"), ("베드로후서", "벧후"), ("요한일서", "요일"), ("요한이서", "요이"),
    ("요한삼서", "요삼"), ("유다서", "유"), ("요한계시록", "계"),
]
_FULL = {full: ab for full, ab in BOOKS}
_ABBR = {ab for _, ab in BOOKS}
# 정식 이름(긴 것부터) 또는 약어 뒤에 '장' 이나 ':' 이 오는 형태
_NAMES = sorted(list(_FULL) + list(_ABBR), key=len, reverse=True)
# 절 하나: 숫자 + (a/b) + (절) + (a/b) — "9절a" 같은 표기도 받는다
_V = r"\d{1,3}[ab]?(?:\s*절)?[ab]?"
_REF = re.compile(
    r"(?P<book>" + "|".join(map(re.escape, _NAMES)) + r")\s*"
    r"(?P<ch>\d{1,3})\s*(?:장|:)\s*"
    r"(?P<vs>" + _V + r"(?:\s*[-~–]\s*" + _V + r")?(?:\s*,\s*" + _V + r"(?:\s*[-~–]\s*" + _V + r")?)*)"
)
_QUOTE = re.compile(r"[\"“”]([^\"“”]{2,60})[\"“”]")


def find_scripture(text):
    """글에서 첫 성경 본문을 찾아 약어 형태(요11:30-44)로. 없으면 빈 문자열."""
    m = _REF.search(text or "")
    if not m:
        return ""
    book = _FULL.get(m.group("book"), m.group("book"))
    vs = re.sub(r"\s*절\s*", "", m.group("vs"))
    vs = re.sub(r"\s*[-~–]\s*", "-", vs)
    vs = re.sub(r"\s*,\s*", ", ", vs).strip()
    return f"{book}{m.group('ch')}:{vs}"


def find_title(text):
    """큰따옴표 안의 설교 제목. 없으면 빈 문자열."""
    m = _QUOTE.search(text or "")
    return m.group(1).strip() if m else ""


if __name__ == "__main__":
    # 간단 시험: 기대값을 코드에 직접 적어 둔다
    cases = {
        '"믿으면 보리라" (요한복음 11장 30-44절)': ("믿으면 보리라", "요11:30-44"),
        '민수기 11장 4-6절, 10-20절 "죄는 예속이다 1"': ("죄는 예속이다 1", "민11:4-6, 10-20"),
        '요한복음 9장 1-12절 "하나님의 일을 나타내시다"': ("하나님의 일을 나타내시다", "요9:1-12"),
        '10월 18일 주일설교 "나타내시다" (요한복음 9:1-12) - 서대일 목사': ("나타내시다", "요9:1-12"),
        '요한일서 4장 7-8절': ("", "요일4:7-8"),
        '출 15:26': ("", "출15:26"),
        '요한복음 5장 1-9절a': ("", "요5:1-9a"),
        '역대하 30장 6-12절': ("", "대하30:6-12"),
        '주일2부예배 (20261025)': ("", ""),
    }
    bad = 0
    for text, (t, s) in cases.items():
        got = (find_title(text), find_scripture(text))
        ok = got == (t, s)
        bad += not ok
        print("OK " if ok else "XX ", text, "->", got)
    raise SystemExit(bad)
